"""
PathBioAgent Scientific Report Generator.

Purpose:
    Convert structured evidence generated by
    PathBioAgent into human-readable scientific
    interpretation.

Design:
    Agent decides.
    Evidence gate decides.
    LLM explains.

The LLM must NOT:
    - rank candidates
    - modify evidence
    - infer unsupported biology
    - claim clinical validity
"""


from typing import Dict, Any

import os

from dotenv import load_dotenv

from langchain_openai import ChatOpenAI


from pathbioagent.llm.evidence_formatter import (
    prepare_report_for_llm,
)



# ============================================================
# System prompt
# ============================================================


SYSTEM_PROMPT = """
You are a computational pathology scientist.

Your task is to explain evidence generated by PathBioAgent.

Strict rules:

1. Only use the provided evidence.
2. Do not invent biological mechanisms.
3. Do not infer causality.
4. Do not claim clinical biomarker validity.
5. Do not change evidence ranking.
6. Clearly separate exploratory findings from validation.

Use concise scientific language.
"""



# ============================================================
# LLM construction
# ============================================================


def _get_chat_model():

    """
    Build normal chat model.

    This is different from query_interpreter.

    query_interpreter:
        structured output

    report_generator:
        natural language generation
    """


    load_dotenv()


    provider = os.getenv(
        "PATHBIO_LLM_PROVIDER",
        "openai",
    ).lower()



    model = os.getenv(
        "PATHBIO_LLM_MODEL",
        "deepseek-flash",
    )



    # --------------------------------------------------------
    # DeepSeek
    # --------------------------------------------------------

    if provider == "deepseek":

        api_key = os.getenv(
            "DEEPSEEK_API_KEY"
        )


        if not api_key:

            raise RuntimeError(
                "Missing DEEPSEEK_API_KEY"
            )


        return ChatOpenAI(

            model=model,

            api_key=api_key,

            base_url=os.getenv(
                "PATHBIO_LLM_BASE_URL",
                "https://api.deepseek.com",
            ),

            temperature=0,

        )


    # --------------------------------------------------------
    # OpenAI
    # --------------------------------------------------------

    api_key = os.getenv(
        "OPENAI_API_KEY"
    )


    if not api_key:

        raise RuntimeError(
            "Missing OPENAI_API_KEY"
        )


    return ChatOpenAI(

        model=model,

        api_key=api_key,

        temperature=0,

    )



# ============================================================
# Evidence preparation
# ============================================================


def _prepare_evidence_text(
    report: Dict[str, Any],
) -> str:

    """
    Convert full PathBioAgent report into
    compact evidence representation.

    No inference happens here.
    """

    clean_report = prepare_report_for_llm(
        report
    )


    return str(
        clean_report
    )



# ============================================================
# Scientific explanation
# ============================================================


def generate_scientific_summary(
    report: Dict[str, Any],
) -> str:

    """
    Generate scientific interpretation
    from structured PathBioAgent evidence.

    Parameters
    ----------
    report:
        Final report generated by LangGraph.

    Returns
    -------
    str:
        Scientific interpretation.
    """


    llm = _get_chat_model()



    evidence_text = (
        _prepare_evidence_text(
            report
        )
    )



    response = llm.invoke(

        [

            {
                "role":
                    "system",

                "content":
                    SYSTEM_PROMPT,
            },


            {
                "role":
                    "user",

                "content":
                    f"""
Generate a concise scientific interpretation.

Query:
{report.get("query")}


Evidence:
{evidence_text}


Please summarize:

1. Supported programs.
2. Magnification-related evidence.
3. Cross-model agreement.
4. Robustness evidence.
5. Important limitations.

""",
            },

        ]

    )


    return response.content